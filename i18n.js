  function norm(s) { return s.replace(/\u2019/g, "'").replace(/\s+/g, " ").trim(); }

  function lookup(n, lang) {
    var dict = DICT[lang];
    if (!dict) return null;
    if (Object.prototype.hasOwnProperty.call(dict, n)) return dict[n];
    var pm = n.match(/^([✓○]) (.+)$/);
    if (pm && Object.prototype.hasOwnProperty.call(dict, pm[2])) return pm[1] + " " + dict[pm[2]];
    for (var i = 0; i < PATTERNS.length; i++) {
      if (PATTERNS[i][0].test(n)) return n.replace(PATTERNS[i][0], PATTERNS[i][1]);
    }
    return null;
  }

  function translateString(s, lang) {
    if (lang === "fr") return s;
    var n = norm(s);
    if (!n) return s;
    var out = lookup(n, lang);
    if (out === null) return s;
    var lead = s.match(/^\s*/)[0];
    var trail = s.match(/\s*$/)[0];
    return lead + out + trail;
  }

  var lang = "fr";
  var records = new WeakMap();

  function processTextNode(node) {
    var p = node.parentNode;
    if (!p || /^(SCRIPT|STYLE|TEXTAREA|OPTION_DISABLED)$/.test(p.nodeName)) return;
    if (p.closest && p.closest("#langSelect")) return;
    var cur = node.nodeValue;
    var rec = records.get(node);
    var src = (rec && cur === rec.out) ? rec.src : cur;
    var out = translateString(src, lang);
    if (out !== cur) node.nodeValue = out;
    records.set(node, { src: src, out: out });
  }

  function processAttributes(root) {
    var els = root.querySelectorAll ? root.querySelectorAll("[placeholder]") : [];
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      if (!el.dataset.phSrc) el.dataset.phSrc = el.getAttribute("placeholder");
      el.setAttribute("placeholder", translateString(el.dataset.phSrc, lang));
    }
  }

  function walk(root) {
    if (root.nodeType === 3) { processTextNode(root); return; }
    if (root.nodeType !== 1) return;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = walker.nextNode())) processTextNode(n);
    processAttributes(root);
  }

  var titleSrc = document.title;
  function applyTitle() { document.title = translateString(titleSrc, lang); }

  function setLang(l) {
    if (!LANGS[l]) l = "fr";
    lang = l;
    document.documentElement.lang = l;
    try { localStorage.setItem("ta_lang", l); } catch (_) {}
    walk(document.body);
    applyTitle();
    var sel = document.getElementById("langSelect");
    if (sel) sel.value = l;
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem("ta_lang"); } catch (_) {}
    var browser = (navigator.language || "fr").slice(0, 2).toLowerCase();
    var start = saved || (LANGS[browser] ? browser : "en");

    var sel = document.createElement("select");
    sel.id = "langSelect";
    sel.setAttribute("aria-label", "Language / Langue");
    sel.style.cssText = "background:#1c2a40;color:#eaf0f8;border:1px solid #34465f;border-radius:8px;padding:8px;font-size:13px;margin-left:8px";
    Object.keys(LANGS).forEach(function (code) {
      var o = document.createElement("option");
      o.value = code;
      o.textContent = LANGS[code];
      sel.appendChild(o);
    });
    sel.addEventListener("change", function () { setLang(sel.value); });
    var host = document.querySelector(".header-top");
    if (host) host.appendChild(sel); else document.body.insertBefore(sel, document.body.firstChild);

    new MutationObserver(function (mutations) {
      mutations.forEach(function (m) {
        if (m.type === "characterData") processTextNode(m.target);
        else m.addedNodes.forEach(function (node) { walk(node); });
      });
    }).observe(document.body, { subtree: true, childList: true, characterData: true });

    setLang(start);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
